import assert from 'node:assert/strict';
import test from 'node:test';
import { readFile } from 'node:fs/promises';
import { buildMagic1000 } from '../../scripts/build-magic-1000-example.mjs';
import { loadGeometryKernel } from '../../scripts/process-benchmarks.mjs';

await loadGeometryKernel();
const { readProjectFile } = await import('../project-io.js');
const { validateProjectFile } = await import('../project-schema.js');
const { collectMaskExportElements, serializeGDS, serializeOASIS } =
  await import('../layout-export.js');
const { parseGDS, flattenGDS } = await import('../gds.js');
const { parseOAS } = await import('../oasis.js');
const { validateRecipeExecution } = await import('../process-recipe-preflight.js');

test('MAGIC-1000 reconstructs every layer through live kernel, with validated history and mask export', async () => {
  const { project, json, validation } = await buildMagic1000();
  assert.equal(validation.pass, true);
  assert.equal(validation.metalLayers, 4);
  assert.equal(validation.vias, 4);
  assert.ok(validation.processNodes > 45);
  assert.ok(validation.bookmarks >= 8);
  assert.equal(project.processRecipe.steps.length, validation.processRecipeSteps);
  assert.equal(project.snapshotBranches.nodes.length, validation.processNodes);
  assert.equal(project.layout.elements.length > 0, true);

  const saved = await readProjectFile({ size: Buffer.byteLength(json), text: async () => json });
  validateProjectFile(saved);
  assert.deepEqual(saved.model, project.model);
  assert.equal(saved.snapshots.length, project.snapshots.length);
  assert.deepEqual(
    validateRecipeExecution(saved.processRecipe.steps, {
      model: saved.model,
      maskState: { layout: saved.layout },
      base: saved.processRecipe.base,
      startMode: 'new-base',
    }).errors,
    [],
  );

  const cells = new Set(['MAGIC1000_LOCAL']);
  const layers = new Set(saved.layout.elements.map((e) => e.layer + '|' + e.datatype));
  const result = collectMaskExportElements({
    layout: saved.layout,
    maskSourceMode: 'file',
    drawMask: saved.drawMask,
    maskTransform: saved.maskTransform,
    maskRoi: null,
    selectedCells: cells,
    selectedLayerKeys: layers,
  });
  assert.ok(result.elements.length >= 13);
  const gds = parseGDS(serializeGDS(result.elements).buffer);
  const oasisBytes = serializeOASIS(result.elements);
  const oas = await parseOAS(oasisBytes.buffer);
  assert.ok(flattenGDS(gds, gds.root).elements.length >= 13);
  assert.ok(flattenGDS(oas, oas.root).elements.length >= 13);

  const serialized = new URL('../examples/magic-1000-mos2-beol.wafercad', import.meta.url);
  // The bundled asset is generated by the dedicated workflow. Validate its
  // content when present; independent kernel reconstruction still runs when
  // authoring without a prebuilt fixture.
  const bytes = await readFile(serialized).catch((error) => {
    if (error.code === 'ENOENT') return null;
    throw error;
  });
  if (bytes) {
    const packed = await readProjectFile({
      size: bytes.byteLength,
      text: async () => bytes.toString('utf8'),
    });
    validateProjectFile(packed);
    assert.deepEqual(packed.model, project.model);
    assert.equal(packed.processRecipe.steps.length, project.processRecipe.steps.length);
  }
});
