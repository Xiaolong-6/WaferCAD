// Inventory live Legacy test owners and the experimental D1 bridge before deletion.
// An occurrence is evidence of a dependency, not proof that it is safe to remove.
import { readdir, readFile } from 'node:fs/promises';
import { join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const scanRoots = ['scripts', 'site/tests', 'site/ui-v2', 'site/controllers'];
// Include editor entrypoints and root-level source which cannot be inferred
// from imports under scripts/tests. The public Pages shim is generated later.
const rootSources = ['site/app.html', 'site/welcome.js', 'site/index.html'];

const legacyEditorFiles = new Set(['site/app-legacy.html', 'site/app.js', 'site/workstation.css']);
const legacyHelper = /\bnewLegacyUi(?:Context|Page)\b/;
const legacyEditor = /(?:app-legacy\.html|\bworkstation\.css\b)/;
const oldD1Bridge = /(?:real-view-bridge\.(?:js|css)|app-v2-real\.html)/;

export function classifyRetirementSurface(path) {
  if (legacyEditorFiles.has(path)) return 'source-only-legacy-editor';
  if (
    path === 'site/app-v2-real.html' ||
    path === 'site/ui-v2/real-section-controls.js' ||
    /^site\/ui-v2\/real-view-bridge\./.test(path)
  )
    return 'experimental-d1';
  // This is consumed by the *production* app.html, not just D1.
  if (path === 'site/ui-v2/real-three-controls.js') return 'shared-production-controls';
  if (path === 'scripts/build-pages-artifact.mjs') return 'published-redirect-owner';
  if (path.startsWith('scripts/') || path.startsWith('site/tests/'))
    return 'scientific-test-or-tooling';
  return 'site-runtime';
}

async function listSources(root, directory) {
  const entries = [];
  const walk = async (path) => {
    for (const item of await readdir(join(root, path), { withFileTypes: true })) {
      const child = join(path, item.name);
      if (item.isDirectory()) await walk(child);
      else if (item.isFile() && /\.(?:mjs|js|html|css)$/.test(item.name)) entries.push(child);
    }
  };
  await walk(directory);
  return entries;
}

export function classifyLegacyOwner(path, content) {
  const testOwner = path.startsWith('scripts/') || path.startsWith('site/tests/');
  const helpers = legacyHelper.test(content);
  const editor = legacyEditor.test(content);
  const bridge = oldD1Bridge.test(content);
  const sourceOnlyEditor = legacyEditorFiles.has(path);
  const surface = classifyRetirementSurface(path);
  const experimentalD1 = surface === 'experimental-d1';
  const sharedProduction = surface === 'shared-production-controls';
  return {
    path,
    testOwner,
    helpers,
    editor,
    bridge,
    requiresReview:
      helpers || editor || bridge || sourceOnlyEditor || experimentalD1 || sharedProduction,
  };
}

export async function auditLegacyRetirementOwners(root = resolve('.')) {
  const paths = [
    ...rootSources,
    ...(await Promise.all(scanRoots.map((dir) => listSources(root, dir)))).flat(),
  ]
    .filter(
      (path) =>
        !path.endsWith('legacy-retirement-owner-audit.mjs') &&
        !path.endsWith('legacy-retirement-owner-audit.test.mjs'),
    )
    .sort();
  const owners = [];
  for (const path of paths) {
    const portable = relative(root, resolve(root, path)).split(sep).join('/');
    const content = await readFile(join(root, path), 'utf8');
    const classification = classifyLegacyOwner(portable, content);
    if (classification.requiresReview)
      owners.push({ ...classification, surface: classifyRetirementSurface(portable) });
  }
  return {
    version: 1,
    owners,
    counts: {
      files: owners.length,
      tests: owners.filter((owner) => owner.testOwner).length,
      helpers: owners.filter((owner) => owner.helpers).length,
      editor: owners.filter((owner) => owner.editor).length,
      bridge: owners.filter((owner) => owner.bridge).length,
      sourceOnlyEditor: owners.filter((owner) => owner.surface === 'source-only-legacy-editor')
        .length,
      experimentalD1: owners.filter((owner) => owner.surface === 'experimental-d1').length,
      siteRuntime: owners.filter((owner) => owner.surface === 'site-runtime').length,
      sharedProductionControls: owners.filter(
        (owner) => owner.surface === 'shared-production-controls',
      ).length,
    },
    warnings: [
      'This is a source reference inventory, not a validated test-equivalence matrix.',
      'Dynamic imports, generated URLs and science scenarios without literal references require separate review.',
      'The production Pages redirect is generated by build-pages-artifact.mjs; source-only Legacy files must not be mistaken for deployed assets.',
      'Experimental D1 acceptance workflows may still execute source-only bridge code, so remove them only after an explicit replacement contract.',
      'real-three-controls.js is used by production app.html: never delete it as part of D1-only cleanup.',
      'Retire each owner only after a production-v2 or canonical scientific assertion has equivalent evidence.',
    ],
  };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(JSON.stringify(await auditLegacyRetirementOwners(), null, 2));
}
