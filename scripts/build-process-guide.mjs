import { readFile, writeFile, access } from 'node:fs/promises';
import { join } from 'node:path';
import { checkDocumentation } from './check-documentation.mjs';
import { buildWikiDiagrams } from './build-wiki-diagrams.mjs';
import { PROCESS_GUIDE } from '../site/process-guide.js';
import { format } from 'prettier';

// Classic script for the portable v2 preview, including direct file:// boot.
// The ESM catalogs remain authoritative; no second set of descriptions/diagrams.
export async function processGuideClassicScript() {
  const sources = await Promise.all(
    ['process-guide.js', 'process-guide-svg.js'].map((name) =>
      readFile(new URL('../site/' + name, import.meta.url), 'utf8'),
    ),
  );
  return format(
    '// Generated by npm run docs:build; edit site/process-guide.js or site/process-guide-svg.js.\n' +
      '(() => {\n' +
      sources.map((source) => source.replace(/^export /gm, '')).join('\n') +
      '\nwindow.WaferCadProcessGuide = Object.freeze({ PROCESS_GUIDE, processGuideKey, processGuideEntry, processGuideSvg });\n})();\n',
    { parser: 'babel', singleQuote: true, printWidth: 100, trailingComma: 'all' },
  );
}

// Generate Wiki operations from exactly the data rendered in the Process panel.
// --check is read-only and fails on drift; --write regenerates the tracked page.
export function processOperationsMarkdown(operations = PROCESS_GUIDE) {
  const lines = [
    '# Process Operations',
    '',
    '[Home](Home) · [Process and Recipes](Process-and-Recipes)',
    '',
    '> All diagrams are schematic. WaferCAD is a geometric process editor, not a calibrated process/electrical TCAD simulator.',
    '',
    'The contextual schematic under **Apply** and this page use the same Process catalog. The current Area selection and active Mask ROI still control the real operation footprint.',
    '',
  ];
  let family = '';
  for (const entry of operations) {
    if (entry.family !== family) {
      family = entry.family;
      lines.push('## ' + family, '');
    }
    lines.push('<a id="' + entry.id + '"></a>', '### ' + entry.title, '');
    lines.push(
      '![Before and after schematic for ' +
        entry.title +
        '](https://raw.githubusercontent.com/Xiaolong-6/WaferCAD/main/docs/wiki/assets/process/' +
        entry.id +
        '.svg?sanitize=true)',
      '',
    );
    lines.push('**Behavior:** ' + entry.summary, '', entry.detail, '');
    lines.push('**Inputs:** ' + entry.parameters, '');
    lines.push(
      '**Changes:** ' +
        ({
          geometry: 'canonical material geometry',
          display: 'display morphology only (ideal 2.5D stack unchanged)',
          annotation: 'non-material annotation only',
          history: 'History metadata only',
        }[entry.effect] || entry.effect),
      '',
    );
    lines.push('**Modeling boundary:** ' + entry.limits, '');
    lines.push('**Example:** ' + entry.example, '');
  }
  lines.push(
    '## More documentation',
    '',
    'See [Mask and ROI](Masks-and-ROI), [History and Recovery](History-Variants-and-Recovery), and [Examples and Modeling Limits](Examples-and-Modeling-Limits).',
    '',
  );
  return lines.join('\n');
}

async function main() {
  const path = join('docs', 'wiki', 'Process-Operations.md');
  const expected = processOperationsMarkdown();
  const mode = process.argv[2] || '--check';
  const classicPath = join('site', 'ui-v2', 'process-guide.generated.js');
  const classicExpected = await processGuideClassicScript();
  if (mode === '--write') {
    await writeFile(classicPath, classicExpected, 'utf8');
    await writeFile(path, expected, 'utf8');
    await buildWikiDiagrams('--write');
    console.log('Wrote ' + path + ' (' + PROCESS_GUIDE.length + ' operations)');
  } else if (mode === '--check') {
    if ((await readFile(classicPath, 'utf8')) !== classicExpected)
      throw Error(classicPath + ' drifted from the shared Process guide. Run npm run docs:build.');
    let actual;
    try {
      actual = await readFile(path, 'utf8');
    } catch {
      throw Error(path + ' missing. Run npm run docs:build.');
    }
    if (actual !== expected)
      throw Error(
        path + ' drifted from site/process-guide.js. Run npm run docs:build and commit the output.',
      );
    const pages = [
      'Home',
      'Getting-Started',
      'Workspace-and-Views',
      'Masks-and-ROI',
      'Process-and-Recipes',
      'Recipe-Code-Tutorial',
      'Recipe-Code-Tutorial-zh-CN',
      'History-Variants-and-Recovery',
      'Import-and-Export',
      'Examples-and-Modeling-Limits',
      'Troubleshooting',
      '_Sidebar',
    ];
    for (const name of pages) await access(join('docs', 'wiki', name + '.md'));
    console.log(
      'Product manual checked: ' +
        PROCESS_GUIDE.length +
        ' operation descriptions and ' +
        pages.length +
        ' authored/navigation pages plus the generated operation reference',
    );
    await buildWikiDiagrams('--check');
    await checkDocumentation();
  } else throw Error('Usage: node scripts/build-process-guide.mjs --check|--write');
}

if (process.argv[1]?.endsWith('build-process-guide.mjs')) await main();
